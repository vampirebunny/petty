// Regenerates src/actor/sky/moonCalendar.ts from astronomy-engine (dev only).
//   npm i -D astronomy-engine && node tools/genMoon.mjs [outFile] [endYear]
import * as A from 'astronomy-engine';
import { writeFileSync } from 'fs';

const out = process.argv[2] ?? 'src/actor/sky/moonCalendar.ts';
const endYear = Number(process.argv[3] ?? 2051);
let q = A.SearchMoonQuarter(A.MakeTime(new Date(Date.UTC(2024, 0, 1))));
const firstQuarter = q.quarter;
const end = Date.UTC(endYear, 0, 1);
const mins = [];
while (q.time.date.getTime() < end) {
  mins.push(Math.round(q.time.date.getTime() / 60000));
  q = A.NextMoonQuarter(q);
}
const gaps = mins.slice(1).map((m, i) => m - mins[i]);
const rows = [];
for (let i = 0; i < gaps.length; i += 16) rows.push('  ' + gaps.slice(i, i + 16).join(', ') + ',');
writeFileSync(
  out,
  `// GENERATED by tools/genMoon.mjs from astronomy-engine (matches the US Naval Observatory phase tables to the minute).
// The principal moon phases from ${new Date(mins[0] * 60000).toISOString().slice(0, 10)} to ${endYear - 1}: new, first quarter, full and last quarter.
// Stored as UTC minutes: the first instant, then the gap in minutes to each next phase. Do not edit by hand.

/** Quarter of the first entry: 0 new, 1 first quarter, 2 full, 3 last quarter. */
export const MOON_FIRST_QUARTER = ${firstQuarter};
/** First phase instant, in minutes since 1970-01-01 UTC. */
export const MOON_BASE_MINUTE = ${mins[0]};
/** Minutes from each phase to the next. */
export const MOON_GAPS: readonly number[] = [
${rows.join('\n')}
];
`,
);
console.log(`wrote ${mins.length} phases to ${out}`);
